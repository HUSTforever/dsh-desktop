/**
 * Renderer-side update badge, injected into the dsh web GUI.
 *
 * The web frontend belongs to the upstream harness repo; rather than fork its
 * UI, the shell injects a self-contained overlay pinned to the bottom-left of
 * the window — visually the sidebar's lower corner. The injected script
 * defines one global, __dshDesktopApplyUpdateState(state), which the main
 * process drives over IPC (bridged by preload as window.dshDesktop) on every
 * update-state change. A MutationObserver re-mounts the overlay if the SPA
 * wipes the body, and each injection is idempotent.
 */

